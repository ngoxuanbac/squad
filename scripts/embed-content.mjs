// Paseo bundles the server entry with esbuild and evaluates it without a plugin directory,
// so roles.json, the prompts and the harness files are embedded as a generated module.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCES = ["roles.json", "content", "server/harness"];

function files(rel) {
  const full = path.join(root, rel);
  if (fs.statSync(full).isFile()) return [rel];
  return fs
    .readdirSync(full)
    .sort()
    .flatMap((name) => files(path.posix.join(rel, name)));
}

export function render() {
  const content = Object.fromEntries(
    SOURCES.flatMap(files).map((rel) => [rel, fs.readFileSync(path.join(root, rel), "utf8").replace(/\r\n/g, "\n")]),
  );
  return [
    "// Generated by scripts/embed-content.mjs from roles.json, content/ and server/harness/. Do not edit; run the script.",
    `export const CONTENT: Record<string, string> = ${JSON.stringify(content, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = path.join(root, "server/hc/content.ts");
  const next = render();
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (current !== next) {
    fs.writeFileSync(file, next);
    console.log("server/hc/content.ts updated");
  }
}
